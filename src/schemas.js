// Every JSON Schema of the API, in one place. They are used for three things at once:
//   1. request validation (Ajv, see validation.js), so the documented limits ARE the enforced limits;
//   2. the OpenAPI 3.1 document behind Swagger UI (openapi.js);
//   3. standalone schemas at GET /schemas/<Name>.json for contract tests in Playwright.
//
// House rules (checked by test/docs.test.js):
//   - every schema node has a `description` and a non-empty `examples` array (plural; never `example`);
//   - strings have a maxLength (or an enum/const/pattern), arrays a maxItems;
//   - objects say `additionalProperties: false` (unknown fields are rejected, not silently dropped);
//   - no $ref: shared pieces are JS constants, so every schema is self-contained.

