/** A stored deck as the API returns it: with the computed totalCards (never stored). */
export function withTotal(deck) {
  const { id, name, theme, description, difficulty, cards, createdAt, updatedAt } = deck;
  const totalCards = cards.reduce((sum, c) => sum + c.quantity, 0);
  return { id, name, theme, description, difficulty, cards, totalCards, createdAt, updatedAt };
}

// ---------- building blocks ----------

const uuid = (description, examples) => ({
  type: 'string', format: 'uuid', pattern: UUID_PATTERN, description, examples,
});

const timestamp = (description) => ({
  type: 'string', format: 'date-time', maxLength: 30, readOnly: true,
  description: `${description} UTC, ISO 8601 with milliseconds. Set by the server; ignored if you send it.`,
  examples: ['2026-01-01T00:01:00.000Z'],
});

const text = (description, minLength, maxLength, examples, extra = {}) => ({
  type: 'string', minLength, maxLength, description, examples, ...extra,
});

const integer = (description, minimum, maximum, examples, extra = {}) => ({
  type: 'integer', minimum, maximum, description, examples, ...extra,
});

